# Типы 

# int
age = 35
print(age)
print(type(age))

# float
salary = 1500.75
print(salary)
print(type(salary))

# str
user_name = "Semen"
print(user_name)
print(type(user_name))

# boolean
is_active = True
print(is_active)
print(type(is_active))

# None
manager = None
print(manager)
print(type(manager))

 
